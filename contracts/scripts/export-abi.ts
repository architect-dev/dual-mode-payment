import { artifacts } from "hardhat";
import fs from "fs";
import path from "path";

// Writes typed `as const` ABIs for viem into the web app.
async function main() {
  const out = path.join(__dirname, "../../web/src/generated");
  fs.mkdirSync(out, { recursive: true });
  const token = await artifacts.readArtifact("DualUSD");
  const indicator = await artifacts.readArtifact("ERC20ConfidentialIndicator");
  const src =
    `// Generated by contracts/scripts/export-abi.ts — do not edit.\n` +
    `export const dualUsdAbi = ${JSON.stringify(token.abi, null, 2)} as const;\n\n` +
    `export const indicatorAbi = ${JSON.stringify(indicator.abi, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(out, "abis.ts"), src);
  console.log(`wrote ${path.join(out, "abis.ts")}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
